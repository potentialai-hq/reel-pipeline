"""Выдаёт готовый рилс автору в пространство контент-завода в iCloud Drive.

Одно место, одинаковые имена у всех роликов, папка ролика всегда «дата название»:

    iCloud Drive/05 Контент-завод/
        КАК ЭТО УСТРОЕНО.txt
        1 Съёмка (сюда класть новое)/         автор кладёт сюда записи с телефона
        2 Готово к публикации/
            2026-11-27 Всю жизнь в стойке/
                ВИДЕО для Instagram.mp4
                ПОДПИСЬ (скопировать в Instagram).txt
        3 Опубликовано/                       сюда папка ролика переезжает после выкладки
        4 Оригиналы/
            2026-11-27 Всю жизнь в стойке.MOV  исходная съёмка, не для публикации
        5 Вставки (перебивки)/                свои кадры для перебивок

Папка берётся из шапки описания (``выдача.папка``, строго «ГГГГ-ММ-ДД Название»),
подпись из первого блока ```text после заголовка «## Подпись», видео из
``cut/<ролик>_instagram.mp4``, оригинал из ``raw/<исходник>``. В подписи последней
строкой идут хэштеги (не больше пяти): автор просил давать их всегда.

Запуск: ``python3 выдать.py Рилсы/<ролик>.md``
После публикации: ``python3 выдать.py Рилсы/<ролик>.md --опубликован``
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

import yaml

ЗАВОД = Path.home() / "Library/Mobile Documents/com~apple~CloudDocs/05 Контент-завод"
СЪЁМКА, ГОТОВО, ОПУБЛИКОВАНО, ОРИГИНАЛЫ, ВСТАВКИ = (
    "1 Съёмка (сюда класть новое)", "2 Готово к публикации", "3 Опубликовано",
    "4 Оригиналы", "5 Вставки (перебивки)")
ВИДЕО = "ВИДЕО для Instagram.mp4"
ПОДПИСЬ = "ПОДПИСЬ (скопировать в Instagram).txt"
ПАМЯТКА = """КОНТЕНТ-ЗАВОД: КАК ЭТО УСТРОЕНО

1 Съёмка (сюда класть новое)   сюда кладёте записи с телефона. Имя файла любое.
2 Готово к публикации          отсюда забираете готовые ролики. Папка = один ролик: дата и название.
3 Опубликовано                 после выкладки перенесите папку ролика сюда.
4 Оригиналы                    исходные записи под теми же датой и названием. Не для публикации.
5 Вставки (перебивки)          ваши кадры для перебивок: море, город, руки, экран.

В папке ролика два файла:
  ВИДЕО для Instagram.mp4                 сам ролик
  ПОДПИСЬ (скопировать в Instagram).txt   текст под роликом, хэштеги в последней строке

КАК ВЫЛОЖИТЬ РОЛИК (на телефоне)
1. «Файлы» -> iCloud Drive -> 05 Контент-завод -> 2 Готово к публикации -> папка ролика.
2. Открыть ВИДЕО, нажать «Поделиться», выбрать «Сохранить видео». Ролик появится в «Фото».
   Пункта «Сохранить видео» нет: подождите, пока у файла пропадёт значок облака (ролик докачается
   на телефон), и нажмите «Поделиться» ещё раз.
3. Открыть ПОДПИСЬ, выделить весь текст, скопировать.
4. Instagram -> «Создать» (плюс) -> Reel -> выбрать ролик из галереи -> «Далее».
5. Вставить подпись. Обложка: кадр из самого начала, там название.
6. «Поделиться».
7. Перенести папку ролика в «3 Опубликовано» или написать Claude: «выложил».

КАК ОТДАТЬ НОВУЮ СЪЁМКУ В РАБОТУ
На телефоне: выделить видео в «Фото» -> «Поделиться» -> «Сохранить в Файлы» ->
iCloud Drive -> 05 Контент-завод -> 1 Съёмка. Потом написать Claude: «возьми новую съёмку».
"""


def main() -> int:
    п = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    п.add_argument("ролик", help="Markdown-файл с описанием ролика")
    п.add_argument("--корень", default=".", help="Папка с cut/")
    п.add_argument("--опубликован", action="store_true", help="Ролик выложен: перенести его папку в «3 Опубликовано»")
    args = п.parse_args()

    текст = Path(args.ролик).read_text(encoding="utf-8")
    шапка = yaml.safe_load(текст.split("---", 2)[1]) or {}
    папка = (шапка.get("выдача") or {}).get("папка")
    if not папка or not re.fullmatch(r"\d{4}-\d{2}-\d{2} \S.*", папка):
        print("Ошибка: в шапке описания нужна выдача.папка вида «2026-11-27 Всю жизнь в стойке» (дата и название)", file=sys.stderr)
        return 1
    if args.опубликован:
        откуда, куда = ЗАВОД / ГОТОВО / папка, ЗАВОД / ОПУБЛИКОВАНО / папка
        if куда.exists():
            print(f"Уже в опубликованных: {куда}")
            return 0
        if not откуда.is_dir():
            print(f"Ошибка: нет папки {откуда}", file=sys.stderr)
            return 1
        откуда.rename(куда)
        print(f"Перенесено: {куда}")
        return 0
    блок = re.search(r"^## Подпись.*?```text\n(.*?)```", текст, flags=re.S | re.M)
    if not блок:
        print("Ошибка: в описании нет раздела «## Подпись» с блоком ```text", file=sys.stderr)
        return 1
    подпись = блок.group(1).strip() + "\n"
    теги = re.findall(r"#\w+", подпись.strip().splitlines()[-1])
    if not теги:
        print("Ошибка: последняя строка подписи без хэштегов; автор просил давать их всегда (до пяти)", file=sys.stderr)
        return 1
    if len(теги) > 5:
        print(f"Ошибка: хэштегов {len(теги)}, справка Instagram допускает не больше пяти", file=sys.stderr)
        return 1
    видео = Path(args.корень).resolve() / "cut" / f"{шапка['ролик']}_instagram.mp4"
    if not видео.is_file():
        print(f"Ошибка: нет готового файла {видео}", file=sys.stderr)
        return 1

    for имя in (СЪЁМКА, ГОТОВО, ОПУБЛИКОВАНО, ОРИГИНАЛЫ, ВСТАВКИ):
        (ЗАВОД / имя).mkdir(parents=True, exist_ok=True)
    (ЗАВОД / "КАК ЭТО УСТРОЕНО.txt").write_text(ПАМЯТКА, encoding="utf-8")
    цель = ЗАВОД / ГОТОВО / папка
    цель.mkdir(exist_ok=True)
    (цель / ПОДПИСЬ).write_text(подпись, encoding="utf-8")
    subprocess.run(["cp", "-c", str(видео), str(цель / ВИДЕО)], check=True)   # клон APFS, места не занимает
    оригинал = Path(args.корень).resolve() / "raw" / шапка["исходник"]
    копия = ЗАВОД / ОРИГИНАЛЫ / f"{папка}{оригинал.suffix}"
    if оригинал.is_file() and not копия.exists():
        subprocess.run(["cp", "-c", str(оригинал), str(копия)], check=True)
    print(f"Выдано: {цель}")
    for файл in sorted(цель.iterdir()):
        print(f"  {файл.name}  {файл.stat().st_size} байт")
    return 0


if __name__ == "__main__":
    sys.exit(main())

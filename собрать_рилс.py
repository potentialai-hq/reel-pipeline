КОРЕНЬ_ДВИЖКА = Path(__file__).resolve().parent


class ОшибкаПользователя(Exception):
    """Ошибка, которую можно показать автору ролика без traceback."""


def _текст_пути(путь: Path, корень: Path) -> str:
    """Возвращает понятный путь, по возможности относительно корня проекта."""
    try:
        return str(путь.relative_to(корень))
    except ValueError:
        return str(путь)


def _сообщение_об_инструменте(имя: str) -> str:
    сообщения = {
        "avconvert": (
            "avconvert пропал между проверкой и запуском (macOS). "
            "Повторите запуск: движок сам переключится на способ приведения "
            "цвета через ffmpeg, если avconvert больше не в PATH."
        ),
        "ffmpeg": "Не найден ffmpeg. Установите его: macOS — brew install ffmpeg, "
        "Windows — choco install ffmpeg-full.",
        "ffprobe": "Не найден ffprobe. Он идёт вместе с ffmpeg — установите ffmpeg.",
        "whisper": (
            "Не найден whisper. Установите распознавание командой: "
            "python3 -m pip install -U openai-whisper"
        ),
    }
    return сообщения.get(имя, f"Не найдена команда «{имя}».")


def запустить(команда: Sequence[str], **kwargs: Any) -> subprocess.CompletedProcess[str]:
    """Запускает внешнюю программу и заменяет ошибку поиска понятной подсказкой."""
    try:
        return subprocess.run(list(команда), check=True, **kwargs)
    except FileNotFoundError as ошибка:
        имя = Path(str(команда[0])).name
        raise ОшибкаПользователя(_сообщение_об_инструменте(имя)) from ошибка


def проверить_ffmpeg() -> None:
    """Отсекает старый ffmpeg до запуска стадий монтажа."""
    результат = запустить(
        ["ffmpeg", "-version"], capture_output=True, text=True, encoding="utf-8"
    )
    try:
        проверить_версию_ffmpeg(результат.stdout or "")
    except ValueError as ошибка:
        raise ОшибкаПользователя(str(ошибка)) from ошибка


def _путь_от_корня(значение: str | Path, корень: Path) -> Path:
    путь = Path(значение)
    return путь if путь.is_absolute() else корень / путь


def _формат(стиль: dict[str, Any]) -> tuple[int, int, int | float]:
    """Читает единый формат ролика из фирменного стиля."""
    параметры = параметры_субтитров(стиль)
    return параметры["ширина"], параметры["высота"], кадров_в_секунду(стиль)


def _проверить_исходник(путь: Path, корень: Path) -> None:
    if путь.is_file():
        return
    имя = путь.name
    raise ОшибкаПользователя(
        f"Не найден исходник «{_текст_пути(путь, корень)}». "
        f"Положите файл «{имя}» в папку «raw/»."
    )


def напечатать_пути(пути: dict[str, Path], корень: Path) -> None:
    """Показывает автору, где движок ожидает и создаёт рабочие файлы."""
    print(f"Исходник: {_текст_пути(пути['исходник'], корень)}")
    print(f"SDR-копия: {_текст_пути(пути['приведённый_цвет'], корень)}")
    print(f"Транскрипт: {_текст_пути(пути['транскрипт'], корень)}")


def _прочитать_поворот(исходник: Path) -> tuple[int | None, int | None, int | None]:
    """Читает rotation именно из side_data, а не делает вывод по размеру потока."""
    результат = запустить(
        [
            "ffprobe",
            "-v",
            "error",
            "-select_streams",
            "v:0",
            "-show_entries",
            "stream=width,height:side_data=rotation",
            "-of",
            "default=nw=1:nk=0",
            str(исходник),
        ],
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    вывод = результат.stdout or ""

    def число(ключ: str) -> int | None:
        совпадение = re.search(rf"(?:^|\n){ключ}=(-?\d+)", вывод)
        return int(совпадение.group(1)) if совпадение else None

    return число("width"), число("height"), число("rotation")


def предупредить_об_ориентации(исходник: Path, корень: Path) -> None:
    """Предупреждает, когда rotation не превращает съёмку в портрет."""
    try:
        ширина, высота, поворот = _прочитать_поворот(исходник)
    except (ОшибкаПользователя, subprocess.CalledProcessError) as ошибка:
        print(
            f"Предупреждение: не удалось проверить ориентацию «{_текст_пути(исходник, корень)}»: "
            f"{ошибка}. Монтаж продолжается.",
            file=sys.stderr,
        )
        return
    портрет = поворот in (-90, 90) or (
        поворот is None
        and ширина is not None
        and высота is not None
        and высота > ширина
    )
    if портрет:
        return
    rotation = "не указан" if поворот is None else str(поворот)
    размеры = (
        f", поток {ширина}×{высота}" if ширина is not None and высота is not None else ""
    )
    print(
        f"Предупреждение: «{_текст_пути(исходник, корень)}» не выглядит портретной "
        f"съёмкой (rotation={rotation}{размеры}). Проверьте ориентацию перед монтажом.",
        file=sys.stderr,
    )


def подготовить_sdr(исходник: Path, sdr: Path) -> None:
    """Создаёт SDR-копию iPhone-исходника, но не трогает уже готовую.

    На macOS с avconvert в PATH способ и команда байт-в-байт совпадают с
    прежним прямым вызовом avconvert. На Windows/Linux без avconvert
    используется способ через ffmpeg (zscale+tonemap) — см. тонмап.py.
    """
    if sdr.is_file():
        return
    sdr.parent.mkdir(parents=True, exist_ok=True)
    try:
        способ = тонмап.выбрать_способ(запустить=запустить)
        тонмап.привести_к_sdr(исходник, sdr, способ, запустить=запустить)
    except тонмап.ОшибкаТонмапа as ошибка:
        raise ОшибкаПользователя(str(ошибка)) from ошибка
    _проверить_результат(sdr, "приведение цвета")


def подготовить_транскрипт(
    исходник: Path, транскрипт: Path, стиль: dict[str, Any]
) -> Path | None:
    """Создаёт транскрипт со словными таймингами и возвращает временный WAV."""
    if транскрипт.is_file():
        return None
    try:
        распознавание = стиль["распознавание"]
        модель = распознавание["модель"]
        язык = распознавание["язык"]
    except (KeyError, TypeError) as ошибка:
        raise ОшибкаПользователя(
            "В фирменном стиле заполните распознавание.модель и распознавание.язык."
        ) from ошибка
    if not isinstance(модель, str) or not модель.strip() or not isinstance(язык, str) or not язык.strip():
        raise ОшибкаПользователя(
            "распознавание.модель и распознавание.язык должны быть непустыми строками."
        )

    транскрипт.parent.mkdir(parents=True, exist_ok=True)
    wav = транскрипт.with_suffix(".wav")
    try:
        запустить(
            [
                "ffmpeg",
                "-y",
                "-v",
                "error",
                "-i",
                str(исходник),
                "-ac",
                "1",
                "-ar",
                "16000",
                "-vn",
                str(wav),
            ]
        )
        запустить(
            [
                "whisper",
                str(wav),
                "--model",
                модель,
                "--language",
                язык,
                "--task",
                "transcribe",
                "--word_timestamps",
                "True",
                "--output_format",
                "json",
                "--output_dir",
                str(транскрипт.parent),
                "--verbose",
                "False",
            ]
        )
    except Exception:
        wav.unlink(missing_ok=True)
        raise
    if not транскрипт.is_file():
        wav.unlink(missing_ok=True)
        raise ОшибкаПользователя(
            "Whisper завершился, но не создал транскрипт «"
            f"{транскрипт}». Проверьте вывод команды whisper и повторите запуск."
        )
    return wav


def записать_план(
    описание: dict[str, Any],
    транскрипт: Path,
    путь_плана: Path,
    *,
    разрешить_пустой_транскрипт: bool = False,
) -> dict[str, Any]:
    """Строит неизменённый формат плана и записывает его рядом с роликом."""
    if not транскрипт.is_file():
        if not разрешить_пустой_транскрипт:
            raise ОшибкаПользователя(
                f"Не найден транскрипт «{транскрипт}» после распознавания. "
                "Повторите запуск, чтобы не собрать ролик без субтитров."
            )
        слова: list[dict[str, Any]] = []
    else:
        try:
            слова = прочитать_слова(транскрипт)
        except (OSError, ValueError, KeyError, TypeError) as ошибка:
            raise ОшибкаПользователя(
                f"Не удалось прочитать транскрипт «{транскрипт}»: {ошибка}"
            ) from ошибка
    try:
        план = собрать_план(описание, слова)
    except ValueError as ошибка:
        raise ОшибкаПользователя(str(ошибка)) from ошибка
    путь_плана.parent.mkdir(parents=True, exist_ok=True)
    путь_плана.write_text(
        json.dumps(план, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return план


def _отрезки_финала(описание: dict[str, Any]) -> list[tuple[float, float]]:
    финал = описание.get("финал", {})
    куски = финал.get("куски", []) if isinstance(финал, dict) else []
    if not isinstance(куски, list):
        raise ОшибкаПользователя("финал.куски должен быть списком отрезков [начало, конец].")

    отрезки: list[tuple[float, float]] = []
    for номер, кусок in enumerate(куски, start=1):
        значение = кусок.get("отрезок") if isinstance(кусок, dict) else кусок
        if (
            not isinstance(значение, (list, tuple))
            or len(значение) != 2
            or any(isinstance(граница, bool) or not isinstance(граница, Real) for граница in значение)
        ):
            raise ОшибкаПользователя(
                f"финал.куски, кусок {номер}: ожидается отрезок [начало, конец]."
            )
        начало, конец = float(значение[0]), float(значение[1])
        if конец <= начало:
            raise ОшибкаПользователя(
                f"финал.куски, кусок {номер}: конец должен быть больше начала."
            )
        отрезки.append((начало, конец))
    return отрезки


def _пути_финала(описание: dict[str, Any], корень: Path) -> dict[str, Path]:
    """Строит те же соглашения путей для отдельного исходника финала."""
    финал = описание["финал"]
    описание_финала = dict(описание)
    описание_финала["исходник"] = финал["исходник"]
    return пути_ролика(описание_финала, корень)


def фильтр_финала(стиль: dict[str, Any]) -> str:
    """Нормализует кусок финала к формату тела, включая единую частоту кадров."""
    ширина, высота, fps = _формат(стиль)
    return (
        f"scale={ширина}:{высота}:force_original_aspect_ratio=increase,"
        f"crop={ширина}:{высота},fps={fps},setsar=1"
    )


def _вырезать_финал(
    исходник: Path,
    отрезки: list[tuple[float, float]],
    временная_папка: Path,
    стиль: dict[str, Any],
) -> list[Path]:
    _, _, fps = _формат(стиль)
    части: list[Path] = []
    for номер, (начало, конец) in enumerate(отрезки):
        часть = временная_папка / f"финал_{номер}.mp4"
        запустить(
            [
                "ffmpeg",
                "-y",
                "-v",
                "error",
                "-ss",
                str(начало),
                "-to",
                str(конец),
                "-i",
                str(исходник),
                "-vf",
                фильтр_финала(стиль),
                "-r",
                str(fps),
                str(часть),
            ]
        )
        части.append(часть)
    return части


def _проверить_результат(путь: Path, стадия: str) -> None:
    """Не даёт успешной внешней команде тихо оставить конвейер без файла."""
    if not путь.is_file():
        raise ОшибкаПользователя(
            f"Стадия «{стадия}» завершилась, но не создала файл «{путь}». "
            "Проверьте сообщения этой стадии и повторите запуск."
        )


def _команда_склейки(файлы: Sequence[Path], база: Path, fps: int | float) -> list[str]:
    """Склеивает декодированные дорожки, не полагаясь на совпадение кодеков."""
    входы = [пара for индекс, файл in enumerate(файлы) for пара in ("-i", str(файл))]
    дорожки = "".join(f"[{индекс}:v][{индекс}:a]" for индекс in range(len(файлы)))
    фильтр = (
        f"{дорожки}concat=n={len(файлы)}:v=1:a=1[v][a];"
        f"[v]fps={fps}[видео]"
    )
    return [
        "ffmpeg",
        "-y",
        "-v",
        "error",
        *входы,
        "-filter_complex",
        фильтр,
        "-map",
        "[видео]",
        "-map",
        "[a]",
        str(база),
    ]


def присоединить_финал(
    тело: Path,
    база: Path,
    описание: dict[str, Any],
    корень: Path,
    стиль: dict[str, Any],
) -> None:
    """Добавляет нормализованные куски финала либо копирует тело без финала."""
    отрезки = _отрезки_финала(описание)
    if not отрезки:
        shutil.copy2(тело, база)
        return

    пути = _пути_финала(описание, корень)
    _проверить_исходник(пути["исходник"], корень)
    предупредить_об_ориентации(пути["исходник"], корень)
    подготовить_sdr(пути["исходник"], пути["приведённый_цвет"])
    with tempfile.TemporaryDirectory(prefix="reel_finale_") as имя:
        временная_папка = Path(имя)
        части = _вырезать_финал(
            пути["приведённый_цвет"], отрезки, временная_папка, стиль
        )
        запустить(_команда_склейки([тело, *части], база, кадров_в_секунду(стиль)))
        _проверить_результат(база, "склейка тела и финала")


def длительность(путь: Path) -> float:
    """Возвращает длительность видео через ffprobe с человеческой ошибкой установки."""
    результат = запустить(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_entries",
            "format=duration",
            "-of",
            "default=nw=1:nk=1",
            str(путь),
        ],
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    try:
        return float((результат.stdout or "").strip())
    except ValueError as ошибка:
        raise ОшибкаПользователя(
            f"Не удалось прочитать длительность файла «{путь}»."
        ) from ошибка


def _параметры_финала(стиль: dict[str, Any]) -> tuple[float, float]:
    try:
        финал = стиль["финал"]
        начало = float(финал["начало_до_конца"])
        хвост = float(финал["хвост"])
    except (KeyError, TypeError, ValueError) as ошибка:
        raise ОшибкаПользователя(
            "В фирменном стиле заполните финал.начало_до_конца и финал.хвост числами."
        ) from ошибка
    return начало, хвост


def _подпись_финала(стиль: dict[str, Any]) -> str:
    финал = стиль.get("финал", {})
    подпись = финал.get("подпись", "") if isinstance(финал, dict) else ""
    return подпись.strip() if isinstance(подпись, str) else ""


def обработать_готовое(
    путь_ролика: Path,
    тело: Path,
    описание: dict[str, Any],
    корень: Path,
    путь_стиля: Path,
    стиль: dict[str, Any],
) -> Path:
    """Прогоняет финал, полировку, музыку и обложку в порядке старого шаблона."""
    имя = str(описание["ролик"])
    папка_cut = корень / "cut"
    база = папка_cut / f"{имя}_full.mp4"
    финал = папка_cut / f"{имя}_final.mp4"
    полировка = папка_cut / f"{имя}_polished.mp4"
    перед_обложкой = папка_cut / f"{имя}_pre.mp4"
    кандидат = папка_cut / f"{имя}_cover.mp4"
    итог = тело
    папка_cut.mkdir(parents=True, exist_ok=True)

    try:
        присоединить_финал(тело, база, описание, корень, стиль)
        финал.unlink(missing_ok=True)
        запустить(
            [sys.executable, str(КОРЕНЬ_ДВИЖКА / "gen_finale.py"), str(база), str(финал), str(путь_стиля)],
            cwd=корень,
        )

        if not финал.is_file():
            if _подпись_финала(стиль):
                _проверить_результат(финал, "gen_finale")
            # Пустая подпись штатно отключает gen_finale. Тогда дальнейшие
            # стадии получают неизменённую базу.
            shutil.copy2(база, финал)

        начало_финала, хвост = _параметры_финала(стиль)
        # Перезвон gen_polish привязан к хопу финала. Без подписи финала нет,
        # и перезвон за три секунды до конца звучит как чужой звук.
        хоп = длительность(финал) - начало_финала - хвост if _подпись_финала(стиль) else -1.0
        музыка = стиль["музыка"]
        try:
            громкость = музыка["громкость"]
            режим = музыка["режим"]
        except (KeyError, TypeError) as ошибка:
            raise ОшибкаПользователя(
                "В фирменном стиле заполните музыка.громкость и музыка.режим."
            ) from ошибка

        запустить(
            [
                sys.executable,
                str(КОРЕНЬ_ДВИЖКА / "gen_polish.py"),
                str(финал),
                str(полировка),
                f"{хоп:.2f}",
            ],
            cwd=корень,
        )
        _проверить_результат(полировка, "gen_polish")
        запустить(
            [
                sys.executable,
                str(КОРЕНЬ_ДВИЖКА / "gen_music.py"),
                str(полировка),
                str(перед_обложкой),
                str(громкость),
                str(режим),
            ],
            cwd=корень,
        )
        _проверить_результат(перед_обложкой, "gen_music")
        кандидат.unlink(missing_ok=True)
        запустить(
            [
                sys.executable,
                str(КОРЕНЬ_ДВИЖКА / "gen_cover.py"),
                str(путь_ролика),
                str(перед_обложкой),
                str(кандидат),
                str(путь_стиля),
            ],
            cwd=корень,
        )
        _проверить_результат(кандидат, "gen_cover")
        кандидат.replace(итог)
        return итог
    finally:
        for промежуточный in (база, финал, полировка, перед_обложкой, кандидат):
            промежуточный.unlink(missing_ok=True)


def _прочитать_вход(
    markdown: Path, стиль_файл: Path, корень: Path
) -> tuple[dict[str, Any], dict[str, Any], dict[str, Path]]:
    """Преобразует ошибки Markdown и стиля в сообщения для автора ролика."""
    try:
        описание = загрузить_ролик(markdown)
        стиль = загрузить_стиль(стиль_файл)
        _формат(стиль)
        пути = пути_ролика(описание, корень)
    except ValueError as ошибка:
        raise ОшибкаПользователя(str(ошибка)) from ошибка
    return описание, стиль, пути


def собрать(путь_ролика: str | Path, путь_стиля: str | Path, корень: str | Path, только_план: bool = False) -> Path:
    """Собирает ролик и возвращает путь плана или готового MP4."""
    корень_проекта = Path(корень).resolve()
    markdown = _путь_от_корня(путь_ролика, корень_проекта)
    стиль_файл = _путь_от_корня(путь_стиля, корень_проекта)
    описание, стиль, пути = _прочитать_вход(markdown, стиль_файл, корень_проекта)
    план = корень_проекта / "plan" / f"{описание['ролик']}.json"
    напечатать_пути(пути, корень_проекта)

    if только_план:
        if not пути["транскрипт"].is_file():
            print(
                "Предупреждение: транскрипта ещё нет, поэтому план записан без "
                "автоматических субтитров.",
                file=sys.stderr,
            )
        записать_план(
            описание,
            пути["транскрипт"],
            план,
            разрешить_пустой_транскрипт=True,
        )
        print(_текст_пути(план, корень_проекта))
        return план

    _проверить_исходник(пути["исходник"], корень_проекта)
    проверить_ffmpeg()
    предупредить_об_ориентации(пути["исходник"], корень_проекта)
    подготовить_sdr(пути["исходник"], пути["приведённый_цвет"])
    wav: Path | None = None
    try:
        wav = подготовить_транскрипт(пути["исходник"], пути["транскрипт"], стиль)
        записать_план(описание, пути["транскрипт"], план)
        тело = корень_проекта / "cut" / f"{описание['ролик']}.mp4"
        запустить(
            [
                sys.executable,
                str(КОРЕНЬ_ДВИЖКА / "stitch_reel.py"),
                str(план),
                str(стиль_файл),
            ],
            cwd=корень_проекта,
        )
        _проверить_результат(тело, "stitch_reel")
        итог = обработать_готовое(
            markdown, тело, описание, корень_проекта, стиль_файл, стиль
        )
    finally:
        if wav is not None:
            wav.unlink(missing_ok=True)
    полоса = кадры_для_проверки(итог)
    print(f"Готово: {_текст_пути(итог, корень_проекта)}")
    if полоса is not None:
        print(f"Кадры для проверки глазами: {_текст_пути(полоса, корень_проекта)}")
    return итог


def кадры_для_проверки(ролик: Path) -> Path | None:
    """Пишет рядом с роликом полосу из трёх кадров: обложка, середина, конец.

    Проверка глазами из чек-листа PIPELINE.md раньше жила только в тексте и
    пропускалась. Полоса делает её одним взглядом: видно, где стоят название и
    субтитры относительно лица и чем заканчивается ролик.
    """
    try:
        всего = длительность(ролик)
    except (ОшибкаПользователя, subprocess.CalledProcessError):
        return None
    моменты = (min(1.0, всего / 2), всего / 2, max(всего - 0.5, 0.0))
    полоса = ролик.with_name(f"{ролик.stem}_кадры.jpg")
    команда = ["ffmpeg", "-y", "-v", "error"]
    for момент in моменты:
        команда += ["-ss", f"{момент:.2f}", "-i", str(ролик)]
    команда += [
        "-filter_complex",
        "[0:v]scale=360:-2[a];[1:v]scale=360:-2[b];[2:v]scale=360:-2[c];[a][b][c]hstack=inputs=3",
        "-frames:v", "1", "-q:v", "4", str(полоса),
    ]
    try:
        subprocess.run(команда, check=True)
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None
    return полоса


def разобрать_аргументы(аргументы: Sequence[str] | None = None) -> argparse.Namespace:
    парсер = argparse.ArgumentParser(
        description="Собрать готовый рилс из Markdown-описания и фирменного стиля."
    )
    парсер.add_argument("ролик", help="Markdown-файл с описанием ролика")
    парсер.add_argument(
        "--стиль", default="Фирменный стиль.md", help="Markdown-файл фирменного стиля"
    )
    парсер.add_argument(
        "--корень", default=".", help="Папка с raw/, raw_sdr/, transcripts/, plan/ и cut/"
    )
    парсер.add_argument(
        "--только-план", action="store_true", help="Записать план и не запускать внешние программы"
    )
    return парсер.parse_args(аргументы)


def main(аргументы: Sequence[str] | None = None) -> int:
    args = разобрать_аргументы(аргументы)
    try:
        собрать(args.ролик, args.стиль, args.корень, args.только_план)
    except ОшибкаПользователя as ошибка:
        print(f"Ошибка: {ошибка}", file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as ошибка:
        команда = " ".join(str(часть) for часть in ошибка.cmd)
        print(f"Ошибка: не удалось выполнить команду: {команда}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

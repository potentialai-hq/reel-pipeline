def стиль_с_умолчаниями_субтитров(вид: str) -> dict[str, Any]:
    """Возвращает полный стиль со значениями по умолчанию для вида субтитров."""
    if вид not in ДОПУСТИМЫЕ_СТИЛИ_СУБТИТРОВ:
        варианты = ", ".join(f"«{вариант}»" for вариант in ДОПУСТИМЫЕ_СТИЛИ_СУБТИТРОВ)
        raise ValueError(f"Неизвестный стиль субтитров {вид!r}. Допустимые значения: {варианты}")
    результат = deepcopy(УМОЛЧАНИЯ)
    результат["субтитры"] = _умолчания_субтитров(вид)
    return результат


def _слить(основа: dict[str, Any], дополнение: dict[str, Any]) -> dict[str, Any]:
    """Возвращает рекурсивное слияние двух словарей, не меняя аргументы."""
    результат = deepcopy(основа)
    for ключ, значение in дополнение.items():
        если_словари = isinstance(результат.get(ключ), dict) and isinstance(значение, dict)
        результат[ключ] = _слить(результат[ключ], значение) if если_словари else deepcopy(значение)
    return результат


def _первый_yaml_блок(текст: str) -> str | None:
    """Извлекает содержимое первого блока ```yaml, не разбирая Markdown."""
    совпадение = re.search(
        r"^[ \t]*```yaml[ \t]*\r?\n(.*?)(?:\r?\n)?^[ \t]*```[ \t]*$",
        текст,
        flags=re.IGNORECASE | re.MULTILINE | re.DOTALL,
    )
    return совпадение.group(1) if совпадение else None


def загрузить_стиль(путь: str | Path) -> dict[str, Any]:
    """Загружает первый YAML-блок из Markdown и дополняет его умолчаниями.

    Отсутствующий файл и Markdown без блока являются нормальным состоянием:
    оба случая возвращают независимую копию :data:`УМОЛЧАНИЯ`.
    """
    файл = Path(путь)
    if not файл.is_file():
        return deepcopy(УМОЛЧАНИЯ)

    текст = файл.read_text(encoding="utf-8")
    блок = _первый_yaml_блок(текст)
    if блок is None:
        return deepcopy(УМОЛЧАНИЯ)

    try:
        данные = yaml.safe_load(блок)
    except yaml.YAMLError as ошибка:
        метка = getattr(ошибка, "problem_mark", None)
        # ``problem_mark.line`` считает от начала YAML, а человеку нужна
        # строка именно Markdown-файла, который он открыл в редакторе.
        смещение = текст[: текст.find(блок)].count("\n")
        строка = смещение + метка.line + 1 if метка is not None else "неизвестна"
        причина = getattr(ошибка, "problem", str(ошибка))
        raise ValueError(
            f"Не удалось прочитать YAML в файле «{файл}», строка {строка}: {причина}"
        ) from ошибка

    if данные is None:
        данные = {}
    if not isinstance(данные, dict):
        raise ValueError(f"YAML в файле «{файл}» должен содержать словарь настроек")
    субтитры = данные.get("субтитры", {})
    вид = субтитры.get("стиль", "тень") if isinstance(субтитры, dict) else "тень"
    умолчания = (
        стиль_с_умолчаниями_субтитров(вид)
        if вид in ДОПУСТИМЫЕ_СТИЛИ_СУБТИТРОВ
        else deepcopy(УМОЛЧАНИЯ)
    )
    return _слить(умолчания, данные)


def кадров_в_секунду(стиль: dict[str, Any]) -> int | float:
    """Возвращает допустимую единую частоту кадров из фирменного стиля."""
    try:
        значение = стиль["формат"]["кадров_в_секунду"]
    except (KeyError, TypeError) as ошибка:
        raise ValueError("В фирменном стиле не задана формат.кадров_в_секунду") from ошибка

    if (
        isinstance(значение, bool)
        or not isinstance(значение, (int, float))
        or not math.isfinite(значение)
        or not 1 <= значение <= 240
    ):
        raise ValueError(
            "формат.кадров_в_секунду должна быть числом от 1 до 240"
        )
    return значение


def параметры_субтитров(стиль: dict[str, Any]) -> dict[str, Any]:
    """Возвращает проверенные параметры отрисовки субтитров.

    Функция отделяет настройки, нужные рендерерам, от полного фирменного
    стиля. ``верх_блока`` нужен «тени», а ``центр_блока`` сохраняет исходную
    геометрию «плашки»: её положение считается от центра блока.
    """
    try:
        субтитры = стиль["субтитры"]
    except (KeyError, TypeError) as ошибка:
        raise ValueError("В фирменном стиле не задан раздел «субтитры»") from ошибка
    if not isinstance(субтитры, dict):
        raise ValueError("Раздел «субтитры» фирменного стиля должен быть словарём")

    вид = субтитры.get("стиль")
    if вид not in ДОПУСТИМЫЕ_СТИЛИ_СУБТИТРОВ:
        варианты = ", ".join(f"«{вариант}»" for вариант in ДОПУСТИМЫЕ_СТИЛИ_СУБТИТРОВ)
        raise ValueError(
            f"Неизвестный стиль субтитров {вид!r}. Допустимые значения: {варианты}"
        )

    try:
        формат = стиль["формат"]
    except (KeyError, TypeError) as ошибка:
        raise ValueError("В фирменном стиле не задан раздел «формат»") from ошибка
    if not isinstance(формат, dict):
        raise ValueError("Раздел «формат» фирменного стиля должен быть словарём")

    def число(
        раздел: dict[str, Any],
        имя_раздела: str,
        ключ: str,
        минимум: float,
        максимум: float,
    ) -> int | float:
        значение = раздел.get(ключ)
        if (
            isinstance(значение, bool)
            or not isinstance(значение, (int, float))
            or not math.isfinite(значение)
            or not минимум <= значение <= максимум
        ):
            raise ValueError(f"{имя_раздела}.{ключ} должно быть числом от {минимум} до {максимум}")
        return значение

    ширина = число(формат, "формат", "ширина", 1, 10000)
    высота = число(формат, "формат", "высота", 1, 10000)
    позиция = число(субтитры, "субтитры", "позиция", 0, 1)
    размер = число(субтитры, "субтитры", "размер", 1, 1000)
    высота_строки = число(субтитры, "субтитры", "высота_строки", 1, 1000)
    символов_в_строке = число(субтитры, "субтитры", "символов_в_строке", 1, 10000)
    строк_максимум = число(субтитры, "субтитры", "строк_максимум", 1, 100)
    пауза_новой_фразы = число(субтитры, "субтитры", "пауза_новой_фразы", 0, 60)
    шрифт = субтитры.get("шрифт")
    if not isinstance(шрифт, str) or not шрифт.strip():
        raise ValueError("субтитры.шрифт должно быть непустым именем файла")

    return {
        "стиль": вид,
        "ширина": int(ширина),
        "высота": int(высота),
        "верх_блока": int(высота * позиция),
        "центр_блока": int(высота * позиция),
        "шрифт": шрифт,
        "размер": int(размер),
        "высота_строки": int(высота_строки),
        "символов_в_строке": int(символов_в_строке),
        "строк_максимум": int(строк_максимум),
        "пауза_новой_фразы": пауза_новой_фразы,
        "цвет_текста": цвет(субтитры.get("цвет_текста")),
        "цвет_активного_слова": цвет(субтитры.get("цвет_активного_слова")),
    }


def путь_к_шрифту(имя: str) -> Path:
    """Возвращает путь к шрифту из ``assets/fonts`` фирменного стиля."""
    путь = Path(имя)
    return путь if путь.is_absolute() else Path(__file__).parent / "assets" / "fonts" / путь


def цвет(строка: str) -> tuple[int, int, int]:
    """Преобразует шестнадцатеричный цвет ``RRGGBB`` в кортеж RGB."""
    if not isinstance(строка, str):
        raise ValueError(f"Некорректный цвет {строка!r}: ожидается строка RRGGBB")
    значение = строка.strip()
    if значение.startswith("#"):
        значение = значение[1:]
    if not re.fullmatch(r"[0-9a-fA-F]{6}", значение):
        raise ValueError(
            f"Некорректный цвет «{строка}»: ожидается шесть шестнадцатеричных символов RRGGBB"
        )
    return tuple(int(значение[номер : номер + 2], 16) for номер in range(0, 6, 2))

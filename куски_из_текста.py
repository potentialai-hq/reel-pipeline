#!/usr/bin/env python3
"""Собирает куски и выверенные слова рилса из сценария по тексту.

Для личных роликов «говорю на ходу»: автор оставляет нужные фразы, а паузы
и границы склеек скрипт находит по энергии звука (правило 3 из PIPELINE.md:
тайминги распознавания нельзя класть в монтаж вслепую).

Сценарий: текстовый файл, строка = оставляемая фраза:

    <секунда первого слова> <секунда последнего слова> [нач=С] [кон=С] | Итоговый текст фразы

``нач`` и ``кон`` задают границы куска вручную, когда соседнее вырезанное
слово стоит вплотную и звук сам границу не покажет.

Секунды берутся из чернового распознавания (начала слов, допуск 0.06 с).
Число слов текста должно совпасть с числом распознанных слов в отрезке;
``∅`` убирает слово из субтитров (звук остаётся), ``~`` склеивает два слова
в одну плашку («были~бороться»).

Запуск:
    python3 куски_из_текста.py <сценарий.txt> <черновик.json> <звук.wav> \
        --слова transcripts/<имя>.json [--пауза 0.7]

Пишет выверенный JSON слов (его читает собрать_рилс.py) и печатает YAML
списка ``куски`` для шапки описания ролика.
"""
from __future__ import annotations

import argparse
import json
import math
import struct
import subprocess
import sys
from pathlib import Path

ШАГ = 0.01          # шаг огибающей, секунды
ПОЛЕ_ДО = 0.12      # сколько тишины оставить перед первым словом куска
ПОЛЕ_ПОСЛЕ = 0.16   # и после последнего


def огибающая(wav: Path) -> list[float]:
    сырьё = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(wav), "-af", "highpass=f=250,lowpass=f=3400",
         "-f", "s16le", "-ac", "1", "-ar", "16000", "-"], capture_output=True, check=True).stdout
    n = len(сырьё) // 2
    x = struct.unpack(f"<{n}h", сырьё)
    кадр = int(16000 * ШАГ)
    уровни = [20 * math.log10((math.sqrt(sum(v * v for v in x[i:i + кадр]) / кадр) + 1) / 32768)
              for i in range(0, n - кадр, кадр)]
    return [sum(уровни[max(0, i - 2):i + 3]) / len(уровни[max(0, i - 2):i + 3]) for i in range(len(уровни))]


def порог_тишины(env: list[float]) -> float:
    s = sorted(env)
    шум, речь = s[int(0.10 * len(s))], s[int(0.80 * len(s))]
    return шум + 0.30 * (речь - шум)


def начало_речи(env, порог, t, назад=0.35):
    """Идёт назад от t, пока звучит речь; возвращает момент, где она началась."""
    i = min(len(env) - 1, int((t + 0.05) / ШАГ)); стоп = max(0, int((t - назад) / ШАГ))
    while i > стоп and not all(v < порог for v in env[max(0, i - 10):i]):
        i -= 1
    return i * ШАГ


def конец_речи(env, порог, t, вперёд=0.9):
    """Идёт вперёд от t, пока звучит речь; возвращает момент, где она стихла."""
    i = int(t / ШАГ); стоп = min(len(env) - 13, int((t + вперёд) / ШАГ))
    while i < стоп and not all(v < порог for v in env[i:i + 12]):
        i += 1
    return i * ШАГ


def тишины(env, порог, a, b, минимум, у_края=0.38):
    """Отрезки тишины внутри [a, b]: в середине не короче ``минимум``, у краёв не короче ``у_края``."""
    найдено, старт = [], None
    от, до = int(a / ШАГ), min(len(env), int(b / ШАГ))
    for i in range(от, до + 1):
        тихо = i < до and env[i] < порог
        if тихо:
            старт = i if старт is None else старт
        elif старт is not None:
            у_края_ли = старт == от or i == до
            if (i - старт) * ШАГ >= (у_края if у_края_ли else минимум):
                найдено.append((старт * ШАГ, i * ШАГ))
            старт = None
    return найдено


def main() -> int:
    п = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    п.add_argument("сценарий"); п.add_argument("черновик"); п.add_argument("звук")
    п.add_argument("--слова", required=True, help="куда записать выверенный JSON слов")
    п.add_argument("--пауза", type=float, default=0.7, help="паузу длиннее этой вырезать")
    args = п.parse_args()

    черновик = json.loads(Path(args.черновик).read_text(encoding="utf-8"))
    слова = [w for s in черновик["segments"] for w in s.get("words", [])]
    env = огибающая(Path(args.звук)); порог = порог_тишины(env)

    # 1. Строки сценария: какие распознанные слова в них входят
    строки: list[dict] = []; ошибки = 0
    for номер, строка in enumerate(Path(args.сценарий).read_text(encoding="utf-8").splitlines(), 1):
        строка = строка.strip()
        if not строка or строка.startswith("#"):
            continue
        времена, текст = строка.split("|", 1)
        поля = времена.split()
        a, b = float(поля[0]), float(поля[1])
        явно = dict(поле.split("=", 1) for поле in поля[2:])   # нач=169.0 кон=169.6: границы куска вручную
        номера = [i for i, w in enumerate(слова) if a - 0.06 <= w["start"] <= b + 0.06]
        плашки = текст.split()
        if len(номера) != len(плашки):
            ошибки += 1
            print(f"строка {номер}: в тексте {len(плашки)} слов, распознано {len(номера)}: "
                  + " ".join(слова[i]["word"].strip() for i in номера), file=sys.stderr)
            continue
        строки.append({"номера": номера, "плашки": плашки, "явно": явно})
    if ошибки:
        return 1

    # 2. Границы строк. Каждая строка начинает свой кусок (смена наезда на новой фразе).
    #    Строки, идущие в записи подряд, делятся в точке наименьшей громкости между ними.
    for к, с in enumerate(строки):
        первое, последнее = слова[с["номера"][0]], слова[с["номера"][-1]]
        подряд = к > 0 and строки[к - 1]["номера"][-1] + 1 == с["номера"][0]
        if "нач" in с["явно"]:
            с["a"] = float(с["явно"]["нач"])
        elif подряд and "кон" not in строки[к - 1]["явно"]:
            от, до = int((первое["start"] - 0.30) / ШАГ), int((первое["start"] + 0.10) / ШАГ)
            с["a"] = min(range(от, до), key=lambda i: env[i]) * ШАГ
            строки[к - 1]["b"] = с["a"]
        else:
            с["a"] = начало_речи(env, порог, первое["start"]) - ПОЛЕ_ДО
        с["b"] = (float(с["явно"]["кон"]) if "кон" in с["явно"]
                  else конец_речи(env, порог, max(последнее["end"] - 0.25, последнее["start"])) + ПОЛЕ_ПОСЛЕ)

    # 3. Паузы внутри строки вырезаются, слова прижимаются внутрь своих кусков
    итог_слов: list[dict] = []; куски: list[tuple[float, float]] = []
    for с in строки:
        a, b = max(0.0, с["a"]), с["b"]
        if куски and a < куски[-1][1]:
            print(f"предупреждение: фраза с {a:.2f} с налезает на предыдущий кусок до {куски[-1][1]:.2f}, "
                  "начало сдвинуто; задайте нач= или объедините строки", file=sys.stderr)
            a = куски[-1][1]
        резы = [[a, None]]
        for т0, т1 in тишины(env, порог, a, b, args.пауза):
            if т0 <= a + 0.011:
                if "нач" not in с["явно"]:      # заданное вручную начало не трогаем
                    резы[0][0] = т1 - ПОЛЕ_ДО
            elif т1 >= b - 0.011:
                if "кон" not in с["явно"]:      # заданный вручную конец (хвост после речи) не трогаем
                    b = т0 + ПОЛЕ_ПОСЛЕ
            else:
                резы[-1][1] = т0 + ПОЛЕ_ПОСЛЕ; резы.append([т1 - ПОЛЕ_ДО, None])
        резы[-1][1] = b
        резы = [(round(x, 2), round(y, 2)) for x, y in резы]
        for i, плашка in zip(с["номера"], с["плашки"]):
            if плашка == "∅":
                continue
            старт, финиш = float(слова[i]["start"]), float(слова[i]["end"])
            кусок = next((r for r in резы if r[0] <= старт <= r[1] - 0.12), None)
            if кусок is None:   # распознавание поставило слово за край куска или в вырезанную паузу
                кусок = min(резы, key=lambda r: min(abs(r[0] - старт), abs(r[1] - старт)))
                старт = кусок[0] + 0.02 if abs(кусок[0] - старт) < abs(кусок[1] - старт) else кусок[1] - 0.35
                старт = max(старт, кусок[0])
            if итог_слов and старт <= итог_слов[-1]["start"]:
                старт = итог_слов[-1]["start"] + 0.04
            финиш = max(старт + 0.10, min(финиш, кусок[1] - 0.02))
            итог_слов.append({"word": " " + плашка.replace("~", " "), "start": round(старт, 2), "end": round(финиш, 2)})
        куски += [r for r in резы if any(r[0] - 0.03 <= w["start"] <= r[1] - 0.10 for w in итог_слов)]

    Path(args.слова).write_text(json.dumps(
        {"text": "".join(w["word"] for w in итог_слов).strip(), "language": "ru",
         "segments": [{"id": 0, "start": итог_слов[0]["start"], "end": итог_слов[-1]["end"],
                       "text": "", "words": итог_слов}]}, ensure_ascii=False, indent=1), encoding="utf-8")
    длина = sum(b - a for a, b in куски)
    print("куски:")
    for a, b in куски:
        print(f"  - [{a:.2f}, {b:.2f}]")
    самый = max(b - a for a, b in куски)
    print(f"# кусков {len(куски)}, слов {len(итог_слов)}, длительность {длина:.1f} с, "
          f"самый длинный кусок {самый:.1f} с, порог тишины {порог:.0f} дБ", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
